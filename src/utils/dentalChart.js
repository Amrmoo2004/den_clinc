/**
 * Generate default 32 teeth with default values:
 * complaint: 'لا توجد شكوى', cost: 0
 */
export const generateDefaultDentalChart = () => {
    return ALL_TEETH_CODES.map((code) => {
        const detail = TEETH_DETAILS[code];
        return {
            toothNumber: code,
            tooth: code,
            complaint: 'لا توجد شكوى',
            complain: 'لا توجد شكوى',
            cost: 0,
            notes: '',
            status: 'healthy',
            jaw: detail.jaw,
            quadrant: detail.quadrant,
        };
    });
};

/**
 * Normalizes existing teeth array into full 32 teeth array,
 * ensuring aliases (tooth/toothNumber, complaint/complain) are always populated.
 */
export const normalizeDentalChart = (existingChart = []) => {
    const existingMap = new Map();

    if (Array.isArray(existingChart)) {
        for (const item of existingChart) {
            const key = (item.toothNumber || item.tooth || '').toUpperCase().trim();
            if (key) {
                existingMap.set(key, item);
            }
        }
    } else if (typeof existingChart === 'object' && existingChart !== null) {
        for (const [key, val] of Object.entries(existingChart)) {
            existingMap.set(key.toUpperCase().trim(), val);
        }
    }

    return ALL_TEETH_CODES.map((code) => {
        const detail = TEETH_DETAILS[code];
        const existing = existingMap.get(code) || {};
        const complaint = existing.complaint !== undefined 
            ? existing.complaint 
            : (existing.complain !== undefined ? existing.complain : 'لا توجد شكوى');
        const cost = Number(existing.cost) || 0;
        const notes = existing.notes || '';
        const status = existing.status || (cost > 0 || complaint !== 'لا توجد شكوى' ? 'treated' : 'healthy');

        return {
            toothNumber: code,
            tooth: code,
            complaint: complaint || 'لا توجد شكوى',
            complain: complaint || 'لا توجد شكوى',
            cost,
            notes,
            status,
            jaw: detail.jaw,
            quadrant: detail.quadrant,
        };
    });
};

/**
 * Merges updates into an existing dental chart.
 * Accepts:
 * - Array of tooth updates e.g. [{ toothNumber: 'UR1', complaint: 'تسوس', cost: 200 }]
 * - Object mapping tooth code to details e.g. { 'UR1': { complaint: 'تسوس', cost: 200 } }
 */
export const mergeDentalChartUpdates = (currentChart = [], updates = []) => {
    const baseChart = normalizeDentalChart(currentChart);
    const updateMap = new Map();

    let itemsToProcess = [];
    if (Array.isArray(updates)) {
        itemsToProcess = updates;
    } else if (typeof updates === 'object' && updates !== null) {
        if (Array.isArray(updates.dentalChart)) {
            itemsToProcess = updates.dentalChart;
        } else if (Array.isArray(updates.teeth)) {
            itemsToProcess = updates.teeth;
        } else {
            // object key-value: { UR1: { complaint: '...', cost: 100 } }
            for (const [code, val] of Object.entries(updates)) {
                itemsToProcess.push({ toothNumber: code, ...(typeof val === 'object' ? val : {}) });
            }
        }
    }

    for (const item of itemsToProcess) {
        if (!item) continue;
        const key = (item.toothNumber || item.tooth || '').toUpperCase().trim();
        if (key && ALL_TEETH_CODES.includes(key)) {
            updateMap.set(key, item);
        }
    }

    return baseChart.map((tooth) => {
        if (updateMap.has(tooth.toothNumber)) {
            const upd = updateMap.get(tooth.toothNumber);
            const complaint = upd.complaint !== undefined 
                ? upd.complaint 
                : (upd.complain !== undefined ? upd.complain : tooth.complaint);
            const cost = upd.cost !== undefined ? Number(upd.cost) : tooth.cost;
            const notes = upd.notes !== undefined ? upd.notes : tooth.notes;
            const status = upd.status !== undefined ? upd.status : tooth.status;

            return {
                ...tooth,
                complaint: complaint || 'لا توجد شكوى',
                complain: complaint || 'لا توجد شكوى',
                cost: isNaN(cost) ? 0 : cost,
                notes: notes || '',
                status: status || 'healthy',
            };
        }
        return tooth;
    });
};

/**
 * Computes summary statistics for a dental chart.
 */
export const calculateDentalChartStats = (chart = []) => {
    let totalCost = 0;
    let teethWithComplaints = 0;
    let teethWithCost = 0;

    for (const t of chart) {
        const cost = Number(t.cost) || 0;
        totalCost += cost;
        if (cost > 0) teethWithCost++;
        if (t.complaint && t.complaint !== 'لا توجد شكوى') {
            teethWithComplaints++;
        }
    }

    return {
        totalTeeth: 32,
        totalCost,
        teethWithComplaints,
        teethWithCost,
        affectedTeethCount: chart.filter((t) => (t.cost > 0) || (t.complaint && t.complaint !== 'لا توجد شكوى')).length,
    };
};
